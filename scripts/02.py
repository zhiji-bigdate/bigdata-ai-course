# ================= 1. 单行注释 =================
# 以 # 开头。# 后面的内容不会被执行，是写给人看的说明。
print('Hello, Python!')  # 注释也可以写在代码后面

# ================= 2. 多行注释 =================
"""
用三引号包起来的文字是多行注释，
可以一次写很多行，
常用来解释一整段代码的作用。
多行注释不会影响程序运行。
"""
print('上面是一段多行注释，程序照常运行')

# ================= 3. 文档字符串 =================
def multiply(a, b):
    """
    这个函数计算两个数的乘积。

    参数：
        a (int)：第一个数
        b (int)：第二个数

    返回：
        int：a 乘以 b 的结果
    """
    return a * b

print('3 × 4 =', multiply(3, 4))
print('--- 下面是用 __doc__ 查看到的文档字符串 ---')
print(multiply.__doc__)
